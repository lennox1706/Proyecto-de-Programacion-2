    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
                String cedula = txtCedula.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());

        if (cedula.isEmpty() || contrasena.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe escribir la cédula y la contraseña.",
                    "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Usuario usuario = repositorio.validarLogin(cedula, contrasena);
            if (usuario == null) {
                JOptionPane.showMessageDialog(this, "Cédula o contraseña incorrectas.",
                        "Acceso denegado", JOptionPane.ERROR_MESSAGE);
                txtContrasena.setText("");
                txtContrasena.requestFocus();
                return;
            }
            // Login correcto: abre el menu y cierra el login.
            new FrmMenu(usuario).setVisible(true);
            dispose();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error al conectar con la base de datos: "
                    + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnIngresarActionPerformed


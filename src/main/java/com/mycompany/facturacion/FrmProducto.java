    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String texto = txtBuscar.getText().trim();

        if (texto.isEmpty()) {
            actualizarTabla();
            return;
        }

        try {
            mostrarProductos(repositorio.buscar(texto));
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                    this, "Error al buscar productos: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String codigo = txtCodigo.getText().trim();
        String descripcion = txtDesripcion.getText().trim();
        String textoPrecio = txtPrecio.getText().trim();
        String textoExistencia = txtExistencia.getText().trim();

        if (codigo.isEmpty() || descripcion.isEmpty()
                || textoPrecio.isEmpty() || textoExistencia.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos");
            return;
        }

        if (codigo.length() > 20 || descripcion.length() > 100) {
            JOptionPane.showMessageDialog(this, "El código de máximo 20 caracteres " + "y la descripción máximo 100");
            return;
        }

        try {
            double precio = Double.parseDouble(textoPrecio);
            int existencia = Integer.parseInt(textoExistencia);

            if (!Double.isFinite(precio) || precio < 0
                    || precio > 99999999.99 || existencia < 0) {
                JOptionPane.showMessageDialog(this, "Ingrese un precio mayor o igual a 0 " + "y una existencia mayor o igual a 0");
                return;
            }

            if (repositorio.buscarPorCodigo(codigo) != null) {
                JOptionPane.showMessageDialog(this, "Ya existe un producto con ese codigo");
                return;
            }

            Producto producto = new Producto(
                    codigo, descripcion, precio, existencia);

            repositorio.guardar(producto);

            limpiarCampos();
            actualizarTabla();

            JOptionPane.showMessageDialog(
                    this, "Producto agregado correctamente.");

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(
                    this, "El precio debe ser un numero y la existencia un entero ");

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                    this, "Error al agregar el producto: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void tblProductoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductoMouseClicked
        int fila = tblProducto.getSelectedRow();

        if (fila >= 0) {
            txtCodigo.setText(tblProducto.getValueAt(fila, 0).toString());
            txtDesripcion.setText(tblProducto.getValueAt(fila, 1).toString());
            txtPrecio.setText(tblProducto.getValueAt(fila, 2).toString());
            txtExistencia.setText(tblProducto.getValueAt(fila, 3).toString());

            txtCodigo.setEditable(false);
        }
    }//GEN-LAST:event_tblProductoMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (tblProducto.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla");
            return;
        }

        String codigo = txtCodigo.getText().trim();
        String descripcion = txtDesripcion.getText().trim();
        String textoPrecio = txtPrecio.getText().trim();
        String textoExistencia = txtExistencia.getText().trim();

        if (descripcion.isEmpty() || textoPrecio.isEmpty()
                || textoExistencia.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos");
            return;
        }

        if (descripcion.length() > 100) {
            JOptionPane.showMessageDialog(this, "La descripción es de máximo 100 caracteres");
            return;
        }

        try {
            double precio = Double.parseDouble(textoPrecio);
            int existencia = Integer.parseInt(textoExistencia);

            if (!Double.isFinite(precio) || precio < 0
                    || precio > 99999999.99 || existencia < 0) {
                JOptionPane.showMessageDialog(this, "Ingrese un precio mayor o igual a 0 " + "y una existencia mayor o igual a 0.");
                return;
            }

            Producto producto = new Producto(codigo, descripcion, precio, existencia);

            repositorio.editar(producto);
            limpiarCampos();
            actualizarTabla();

            JOptionPane.showMessageDialog(this, "Producto actualizado correctamente");

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "El precio debe ser un numero y la existencia un entero");

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error al editar el producto: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblProducto.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(
                    this, "Seleccione un producto de la tabla.");
            return;
        }

        String codigo = tblProducto.getValueAt(fila, 0).toString();

        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Desea eliminar el producto " + codigo + "?",
                "Eliminar producto",
                JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {
            try {
                repositorio.eliminar(codigo);

                limpiarCampos();
                actualizarTabla();

                JOptionPane.showMessageDialog(
                        this, "Producto eliminado correctamente.");

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(
                        this, "No se pudo eliminar el producto: "
                        + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
        limpiarCampos();
    }//GEN-LAST:event_btnLimpiarActionPerformed
    private void actualizarTabla() {
        try {
            mostrarProductos(repositorio.listar());
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                    this, "Error al cargar productos: " + ex.getMessage());
        }
    }

    private void mostrarProductos(List<Producto> productos) {
        modeloTabla.setRowCount(0);

        for (Producto producto : productos) {
            modeloTabla.addRow(new Object[]{
                producto.getCodigo(),
                producto.getDescripcion(),
                producto.getPrecio(),
                producto.getExistencia()
            });
        }
    }

    private void limpiarCampos() {
        tblProducto.clearSelection();

        txtCodigo.setText("");
        txtDesripcion.setText("");
        txtPrecio.setText("");
        txtExistencia.setText("");

        txtCodigo.setEditable(true);
    }


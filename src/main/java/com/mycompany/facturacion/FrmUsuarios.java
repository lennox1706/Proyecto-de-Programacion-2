    private void llenarTabla(List<Usuario> usuarios) {
        modelo.setRowCount(0);
        for (Usuario u : usuarios) {
            modelo.addRow(new Object[]{u.getCedula(), u.getNombre()});
        }
    }

    private void mostrarTodos() {
        try {
            llenarTabla(repositorio.listar());
            txtBuscar.setText("");
        } catch (SQLException ex) {
            mostrarError("Error al consultar usuarios: " + ex.getMessage());
        }
    }

    private void buscar() {
        String texto = txtBuscar.getText().trim();
        if (texto.isEmpty()) {
            mostrarTodos();
            return;
        }
        try {
            llenarTabla(repositorio.buscar(texto));
        } catch (SQLException ex) {
            mostrarError("Error al buscar: " + ex.getMessage());
        }
    }

    private void cargarSeleccion() {
        int fila = tblUsuarios.getSelectedRow();
        if (fila < 0) {
            return;
        }
        String cedula = modelo.getValueAt(fila, 0).toString();
        try {
            Usuario u = repositorio.buscarPorCedula(cedula);
            if (u != null) {
                txtCedula.setText(u.getCedula());
                txtNombre.setText(u.getNombre());
                txtContrasena.setText(u.getContrasena());
                txtCedula.setEditable(false);
            }
        } catch (SQLException ex) {
            mostrarError("Error al cargar el usuario: " + ex.getMessage());
        }
    }

    private Usuario leerFormulario() {
        String cedula = txtCedula.getText().trim();
        String nombre = txtNombre.getText().trim();
        String contrasena = new String(txtContrasena.getPassword()).trim();
        if (cedula.isEmpty() || nombre.isEmpty() || contrasena.isEmpty()) {
            mostrarError("Debe completar cédula, nombre y contraseña.");
            return null;
        }
        return new Usuario(cedula, nombre, contrasena);
    }

    private void agregar() {
        if (!txtCedula.isEditable()) {
            mostrarError("Hay un usuario seleccionado. Use Limpiar para agregar uno nuevo.");
            return;
        }
        Usuario u = leerFormulario();
        if (u == null) {
            return;
        }
        try {
            if (repositorio.buscarPorCedula(u.getCedula()) != null) {
                mostrarError("Ya existe un usuario con esa cédula.");
                return;
            }
            repositorio.guardar(u);
            JOptionPane.showMessageDialog(this, "Usuario agregado correctamente.");
            limpiar();
            mostrarTodos();
        } catch (SQLException ex) {
            mostrarError("Error al guardar: " + ex.getMessage());
        }
    }

    private void guardarCambios() {
        if (tblUsuarios.getSelectedRow() < 0 || txtCedula.isEditable()) {
            mostrarError("Seleccione un usuario de la tabla para editarlo.");
            return;
        }
        Usuario u = leerFormulario();
        if (u == null) {
            return;
        }
        try {
            repositorio.editar(u);
            JOptionPane.showMessageDialog(this, "Cambios guardados correctamente.");
            limpiar();
            mostrarTodos();
        } catch (SQLException ex) {
            mostrarError("Error al editar: " + ex.getMessage());
        }
    }

    private void eliminar() {
        if (tblUsuarios.getSelectedRow() < 0) {
            mostrarError("Seleccione un usuario de la tabla para eliminarlo");
            return;
        }
        String cedula = txtCedula.getText().trim();
        if (cedula.equals(cedulaActual)) {
            mostrarError("No puede eliminar el usuario con el que inicio sesion");
            return;
        }
        try {
            if (repositorio.listar().size() <= 1) {
                mostrarError("No se puede eliminar el unico usuario");
                return;
            }
        } catch (SQLException ex) {
            mostrarError("Error al verificar usuarios: " + ex.getMessage());
            return;
        }
        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Desea eliminar el usuario con cedula " + cedula + "?",
                "Confirmar", JOptionPane.YES_NO_OPTION);
        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            repositorio.eliminar(cedula);
            JOptionPane.showMessageDialog(this, "Usuario eliminado correctamente");
            limpiar();
            mostrarTodos();
        } catch (SQLException ex) {
            mostrarError("Error al eliminar: " + ex.getMessage());
        }
    }


    private void limpiar() {
        txtCedula.setText("");
        txtNombre.setText("");
        txtContrasena.setText("");
        txtCedula.setEditable(true);
        tblUsuarios.clearSelection();
        txtCedula.requestFocus();
    }

    private void mostrarError(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Aviso", JOptionPane.WARNING_MESSAGE);
    }
